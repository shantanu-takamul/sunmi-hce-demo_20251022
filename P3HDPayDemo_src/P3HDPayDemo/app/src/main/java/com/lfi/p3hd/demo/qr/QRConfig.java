    /** Fallback QR lifetime, used only when the response carries no timestamps. */
    public static final long QR_TIMEOUT_MS    = 300_000L;

    /**
     * How often to ask whether the QR has been paid.
     *
     * Was 5 s, which is fine for merely reporting a sale but not for acting on one:
     * the whole pre-settlement cancel window is about ten seconds from the payment,
     * so every second of polling lag is a second the operator loses. A 5 s interval
     * burned over half the window before the success screen even appeared. See
     * SETTLEMENT_WINDOW_MS.
     *
     * The cost is roughly 2.5x the status calls per QR (a 180 s window goes from
     * ~36 to ~90). That is the trade being made, deliberately: a cancel button that
     * usually works is worth more than the saved requests.
     */
    public static final long POLL_INTERVAL_MS = 2_000L;

    // -------------------------------------------------------------------------
    // Acquirer commission
    //
    // commissionAmount is the acquirer's cut of a sale, in fils: the merchant is
    // credited amount − commissionAmount, and the QR carries the split so
    // settlement and any later return reverse the same figures.
    //
    // This POS has no commission model — there is no operator input for it and no
    // merchant agreement behind it — so it generates every QR at zero. The field
    // is still sent explicitly rather than omitted: the gateway defaults a missing
    // commissionAmount to 0, but stating it keeps the request self-describing and
    // gives a single place to change if this terminal ever earns a commission.
    //
    // Whatever is sent here must come back on the return, which is why the value
    // rides the intent chain from generate to the success screen rather than being
    // re-derived. See ReturnApi.Call#commissionFils.
    // -------------------------------------------------------------------------

    /** Commission applied to a QR generated by this terminal, in fils. */
    public static final long QR_COMMISSION_AMOUNT = 0L;

    // -------------------------------------------------------------------------
    // The cancel window
    //
    // CANCEL is only accepted while the original transaction is UNSETTLED:
    //
    //   422 VALIDATION_ERROR {"field":"originalTransactionId"}
    //       "CANCEL is only allowed within the pre-settlement cancel window
    //        of the original transaction"
    //
    // QA settles a P2M payment about ten seconds after it is created. Measured on
    // one transaction, 2026-08-14:
    //   createdAt 19:37:01.320Z -> settledAt 19:37:11.367Z  (10.047 s)
    // A cancel that reached the gateway 88 ms after settledAt was refused, so the
    // cutoff is genuinely the settlement instant and not a grace period around it.
    //
    // ONE data point. Treat SETTLEMENT_WINDOW_MS as an estimate for the countdown
    // only — never as permission. Authority is the transaction's own
    // settlementStatus, which the history response carries; see isSettled.
    //
    // The window is measured from the gateway's createdAt, NOT from when polling
    // noticed the payment. Those differ by up to POLL_INTERVAL_MS, and anchoring to
    // detection is what caused the 88 ms miss: the countdown began 5.57 s into a
    // 10 s window and showed the operator ten seconds that were not there.
    // -------------------------------------------------------------------------

    /** Observed delay between a P2M payment being created and settled. */
    public static final long SETTLEMENT_WINDOW_MS = 10_000L;

    /**
     * Stop offering CANCEL this far before settlement is predicted.
     *
     * Covers the request's own flight time plus the error in a window estimated
     * from a single sample. Without it the POS offers a button whose call arrives
     * after the cutoff, which is a worse experience than not offering it at all.
     */
    public static final long CANCEL_SAFETY_MARGIN_MS = 1_500L;

    /** True when the gateway reports this transaction as settled — cancel is over. */
    public static boolean isSettled(JSONObject tx) {
        return "SETTLED".equals(tx.optString("settlementStatus", ""));
    }

    /**
     * The {@link android.os.SystemClock#elapsedRealtime()} value at which the POS
     * must stop offering CANCEL, or 0 when it must not be offered at all.
     *
     * Derived from the transaction's own {@code createdAt} so the countdown
     * reflects the real remaining window rather than the moment we happened to
     * notice the payment. Returns 0 — no cancel — whenever the answer cannot be
     * trusted: already settled, no parseable createdAt, or the window is spent.
     * Offering nothing is strictly better than offering a button that fails.
     *
     * @param nowElapsed elapsedRealtime() sampled alongside this call
     */
    public static long cancelDeadlineElapsed(JSONObject tx, long nowElapsed) {
        if (isSettled(tx)) return 0L;

        long createdAt = parseIsoUtc(tx.optString("createdAt", ""));
        if (createdAt <= 0) return 0L;

        // Wall clock is unavoidable here: it is the only clock shared with the
        // gateway. A device running behind the server would over-report the
        // remaining window, so clamp a negative age to zero rather than trusting it.
        long ageMs = System.currentTimeMillis() - createdAt;
        if (ageMs < 0) ageMs = 0L;

        long remaining = SETTLEMENT_WINDOW_MS - CANCEL_SAFETY_MARGIN_MS - ageMs;
        return remaining <= 0L ? 0L : nowElapsed + remaining;
    }

    // -------------------------------------------------------------------------
    // POS amount bounds
    //
    // The terminal refuses out-of-range amounts locally so no QR is ever shown
    // for a sale the gateway would reject. These are POS-side guards, not the
    // authoritative limits: the environment's configured minimum and maximum are
