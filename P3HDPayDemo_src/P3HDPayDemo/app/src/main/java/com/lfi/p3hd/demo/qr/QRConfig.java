    /**
     * The merchant's TECHNICAL wallet (CUAE prefix, Central Bank layer).
     *
     * QR generation routes on this wallet, NOT on the merchant's
     * MERCHANT_COLLECTION wallet. Technical wallet = routing address;
     * collection wallet = settlement account.
     *
     * ---------------------------------------------------------------------
     * THIS IS ENVIRONMENT DATA, NOT A CONSTANT.
     *
     * QA is periodically rebuilt and every wallet in it is destroyed. When
     * that happens this id stops resolving and EVERY QR fails, with no code
     * change on our side. It has already happened twice:
     *   CUAE2DFD30048E → CUAEBBEFEB2B02 → CUAECA69D6D9C7 (current)
     *
     * Do not debug the app first. Read the error:
     *
     *   HTTP 401                                  → API key. ApiKeyManager
     *                                               self-heals; if it does not,
     *                                               the operator login failed.
     *   HTTP 400 "Acquirer QR must be generated
     *            for the merchant's technical
     *            wallet"                          → wallet EXISTS but is the
     *                                               wrong type (you used the
     *                                               NIXX collection wallet).
     *   HTTP 400 "Validation failed" (generic)    → wallet DOES NOT EXIST.
     *                                               QA was rebuilt. Fix below.
     *
     * The generic-vs-specific distinction is the whole diagnosis: a wallet of
     * the wrong type still resolves, so it gets the specific message. The
     * generic one means lookup found nothing.
     *
     * ---------------------------------------------------------------------
     * TO FIND THE NEW VALUE
     *
     * Technical wallets are NOT returned by the LFI-scoped wallet list —
     * X-LFI-ID restricts results to the LFI's own NIXX wallets and hides every
     * CUAE one. Omit that header to query the Central Bank layer:
     *
     *   TOKEN=$(curl -s -X POST \
     *     https://mithril-qa-backend.takamul.cc/web/api/v1/auth/login \
     *     -H 'Content-Type: application/json' \
     *     -d '{"username":"test-global-admin","password":"12345","realm":"cbuae"}' \
     *     | python3 -c 'import json,sys;print(json.load(sys.stdin)["access_token"])')
     *
     *   curl -s -H "Authorization: Bearer $TOKEN" \
     *     'https://mithril-qa-backend.takamul.cc/web/api/v1/wallets?walletType=TECHNICAL'
     *
     * Pick a CUAE id and confirm it before shipping:
     *
     *   curl -s -X POST "https://mithril-qa-backend.takamul.cc\
     *   /lfi-gateway/api/v1/qr/generate?requestId=$(uuidgen)" \
     *     -H 'X-LFI-ID: acq-NI' -H "X-LFI-API-KEY: <key>" \
     *     -H 'Content-Type: application/json' \
     *     -d '{"messageTypeId":"cbdc.231.101.01","qrType":"DYNAMIC",
     *          "walletId":"CUAE...","amount":5000,"currency":"AED",
     *          "terminalId":"TERM001"}'
     *
     * Requires Cloudflare WARP with a live Access session — note that the
     * tunnel being up does NOT mean the session is authenticated; an expired
     * session shows up as a 302 to cloudflareaccess.com.
     *
     * NOTE: creating a new merchant is NOT the fix and is not available to this
     * account. POST /web/api/v1/merchants 403s for the cbuae CB admin because
     * the acquirer is taken from the Keycloak session, not X-LFI-ID; it needs
     * an acq-NI realm session with MSP_ADMIN. Reuse an existing technical
     * wallet instead.
     *
     * ---------------------------------------------------------------------
     * NO REBUILD REQUIRED
     *
     * Settings > Wallet ID overrides this value at runtime — see
     * QRPayActivity#generateQR and NFCPayActivity#generateQRAndOpenHce, which both
     * fall back here only when the pref is empty. Prefer the pref for a QA
     * repoint; update this constant so fresh installs get a working default.
     *
     * Current value verified against qr/generate on 2026-08-10 —
     * merchant "Sujan Fruits and Vegetables", MCC 5411.
     * Spare, also verified the same day: CUAE265185629C
     * ("London Dairy Milk Products", MCC 5451).
     */
