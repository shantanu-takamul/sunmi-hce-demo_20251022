    /**
     * Pulls the EMV QR payload out of a /qr/generate response.
     *
     * The gateway renamed this field from {@code emvPayload} to {@code emvCode}
     * (Mithril 5.x — see AcquirerQrGenerateResponse). Older envs may still send
     * the old name, so accept either.
     */
    public static String emvFrom(JSONObject json) throws JSONException {
        String emv = json.optString("emvCode", "");
        if (emv.isEmpty()) emv = json.optString("emvPayload", "");
        if (emv.isEmpty()) throw new JSONException("response has neither emvCode nor emvPayload");
        return emv;
    }

    /**
     * Reads a counterparty wallet id out of a history transaction.
     *
     * The two environments disagree on shape. Demo returns the wallets flat on
     * the transaction; QA (verified against the live QA history on 2026-08-11)
     * omits them entirely and carries them inside a {@code movements[]} array:
     *
     * <pre>
     * { "transactionId": "...", "transactionType": "PAY_TO_MERCHANT",
     *   "movements": [ { "payerWalletId": "FABX...", "payerWalletType": "RETAIL",
     *                    "payeeWalletId": "CUAE...", "payeeWalletType": "TECHNICAL" } ] }
     * </pre>
     *
     * Reading only the flat field yields an empty string on QA, which shows up as
     * "From: —" in the list and — far worse — sends an empty wallet id in a
     * refund. Prefer the flat field so demo is untouched, then fall back to the
     * first movement.
     *
     * @param field either {@code payerWalletId} or {@code payeeWalletId}
     */
    public static String walletFrom(JSONObject tx, String field) {
        String flat = tx.optString(field, "");
        if (!flat.isEmpty()) return flat;
        JSONArray movements = tx.optJSONArray("movements");
        if (movements == null || movements.length() == 0) return "";
        JSONObject first = movements.optJSONObject(0);
        return first == null ? "" : first.optString(field, "");
    }

    /**
     * The refund/cancel entries attached to a history transaction.
     *
     * QA (Mithril 5.x, TransactionRecordDto verified 2026-08-14) calls this array
     * {@code returns}, because it now holds both REFUND and CANCEL rows. Demo still
     * calls it {@code refunds}. Reading only the old name means QA never reports a
     * transaction as already returned, so the Refund button stays live on a
     * transaction that has already been refunded — a double-refund invitation.
     */
    public static JSONArray returnsOf(JSONObject tx) {
        JSONArray returns = tx.optJSONArray("returns");
        return returns != null ? returns : tx.optJSONArray("refunds");
    }

    /** Status of one {@link #returnsOf} entry — {@code status} on QA, {@code refundStatus} on demo. */
    public static String returnStatusOf(JSONObject entry) {
        String status = entry.optString("status", "");
        return status.isEmpty() ? entry.optString("refundStatus", "") : status;
    }

    /** Id of the transaction a return created — {@code returnTransactionId} on QA. */
    public static String returnTxIdOf(JSONObject entry) {
        String id = entry.optString("returnTransactionId", "");
        return id.isEmpty() ? entry.optString("refundTransactionId", "") : id;
    }

    /**
     * The acquirer commission carried on a transaction, in fils.
     *
     * QA reports it under {@code settlement}, which only appears once the sale has
     * settled; before that there is nothing to read and 0 is the honest answer for
     * a terminal that generates every QR at {@link #QR_COMMISSION_AMOUNT}. Prefer
     * the commission the QR was generated with when the caller still has it — this
     * is the fallback for a transaction read back out of history.
     */
    public static long commissionFrom(JSONObject tx) {
        JSONObject settlement = tx.optJSONObject("settlement");
        if (settlement != null) return settlement.optLong("commissionAmount", 0L);
        return tx.optLong("commissionAmount", 0L);
    }

    /**
     * OkHttp client for gateway calls.
     *
     * Redirects are off on purpose: every *.takamul.cc backend sits behind
     * Cloudflare Access, and a device without WARP gets a 302 to the Access login
     * page. Following it would return HTML with a 200, which then fails JSON
     * parsing and looks like a malformed gateway response. Leaving the 302 intact
     * lets the caller report the real cause. No gateway API legitimately redirects.
     */
    public static OkHttpClient newHttpClient() {
        return new OkHttpClient.Builder()
            .followRedirects(false)
            .followSslRedirects(false)
            .build();
    }

    /**
     * True when a response body is a Cloudflare Access / WARP gate page rather
     * than anything the gateway produced.
     */
    public static boolean looksLikeAccessGate(String responseBody) {
        if (responseBody == null || responseBody.isEmpty()) return false;
        String head = responseBody.length() > 512 ? responseBody.substring(0, 512) : responseBody;
        String lower = head.toLowerCase(Locale.US);
        return lower.contains("warp client")
            || lower.contains("cloudflare access")
            || lower.contains("cloudflareaccess.com")
            || lower.startsWith("<!doctype")
            || lower.startsWith("<html");
    }

    /**
     * How long the gateway says this QR stays valid, in ms.
     *
     * Derived from the response's own {@code expiresAt - generatedAt} pair rather
     * than from the device clock, so a POS with a skewed clock still counts down
     * the right amount. The gateway currently grants 180s while QR_TIMEOUT_MS is
     * 300s — counting down the local constant leaves a dead QR on screen for two
     * minutes. Falls back to QR_TIMEOUT_MS if the timestamps are missing.
     */
    public static long ttlMsFrom(JSONObject json) {
        long generatedAt = parseIsoUtc(json.optString("generatedAt", ""));
        long expiresAt   = parseIsoUtc(json.optString("expiresAt", ""));
        if (generatedAt > 0 && expiresAt > generatedAt) {
            long ttl = expiresAt - generatedAt;
            // Guard the countdown UI against an implausible window.
            if (ttl >= MIN_QR_TTL_MS && ttl <= MAX_QR_TTL_MS) return ttl;
        }
        return QR_TIMEOUT_MS;
    }

    /**
     * Parses the gateway's ISO-8601 UTC timestamps, e.g.
     * {@code 2026-07-30T07:47:59.645825943Z}. Returns -1 when unparseable.
     *
     * Fractional seconds are dropped: they carry nanosecond precision, which
     * SimpleDateFormat cannot read, and second precision is enough for a timer.
     * SimpleDateFormat is used rather than java.time because minSdk is 25.
     */
    public static long parseIsoUtc(String timestamp) {
        if (timestamp.length() < 19) return -1;
        try {
            SimpleDateFormat fmt = new SimpleDateFormat("yyyy-MM-dd'T'HH:mm:ss", Locale.US);
            fmt.setTimeZone(TimeZone.getTimeZone("UTC"));
            Date parsed = fmt.parse(timestamp.substring(0, 19));
            return parsed == null ? -1 : parsed.getTime();
        } catch (ParseException e) {
            return -1;
        }
    }

    /**
     * Human-readable text for a failed gateway call.
     *
     * Errors come back as {@code {"code":"AUTH_TOKEN_MISSING","defaultMessage":"..."}},
     * which is far more useful on the POS screen than a bare status code.
     */
    public static String errorTextOf(String responseBody, int httpCode) {
        if (looksLikeAccessGate(responseBody)) {
            return "blocked by Cloudflare Access — connect the WARP client on this device";
        }
        try {
            JSONObject json = new JSONObject(responseBody);
            String msg  = json.optString("defaultMessage", json.optString("message", ""));
            String code = json.optString("code", "");
            if (!msg.isEmpty()) {
                return code.isEmpty() ? msg : msg + " (" + code + ")";
            }
        } catch (Exception ignored) {
            // Not JSON (e.g. a Cloudflare Access redirect body) — fall through.
        }
        return "HTTP " + httpCode;
    }

